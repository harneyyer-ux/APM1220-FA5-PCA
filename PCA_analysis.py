import pandas as pd

# Load the uploaded dataset
df = pd.read_csv("/world-happiness-report-2021.csv")

# Select the seven required quantitative variables
variables = [
    "Ladder score",
    "Logged GDP per capita",
    "Social support",
    "Healthy life expectancy",
    "Freedom to make life choices",
    "Generosity",
    "Perceptions of corruption"
]

X = df[variables].copy()

# Part A1: Dataset information
print("PART A1: DATASET INFORMATION")
print("Number of observations:", X.shape[0])
print("Number of selected variables:", X.shape[1])
print("Missing values:", X.isnull().sum().sum())
print("\nVariables:")
print(X.columns.tolist())

# Part A2: Descriptive statistics
print("\nPART A2: MEAN AND STANDARD DEVIATION")
descriptive_stats = pd.DataFrame({
    "Mean": X.mean(),
    "Standard Deviation": X.std(ddof=1)
})
print(descriptive_stats.round(3))

# Part A4: Correlation matrix
print("\nPART A4: CORRELATION MATRIX")
correlation_matrix = X.corr()
print(correlation_matrix.round(3))


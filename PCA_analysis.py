import numpy as np
from sklearn.preprocessing import StandardScaler

# ==========================================
# PART B: PRINCIPAL COMPONENT ANALYSIS (PCA)
# ==========================================

# 1. Standardize the seven selected variables
scaler = StandardScaler()
Z = scaler.fit_transform(X)

# 2. Calculate the correlation matrix of standardized variables
R = np.corrcoef(Z, rowvar=False)

# 3. Perform eigen-decomposition of the correlation matrix
eigenvalues, eigenvectors = np.linalg.eigh(R)

# Arrange eigenvalues from largest to smallest
order = np.argsort(eigenvalues)[::-1]
eigenvalues = eigenvalues[order]
eigenvectors = eigenvectors[:, order]

# 4. Calculate variance proportions and cumulative proportions
variance_proportion = eigenvalues / eigenvalues.sum()
cumulative_proportion = np.cumsum(variance_proportion)

# 5. Create the variance summary table
components = [f"PC{i}" for i in range(1, len(eigenvalues) + 1)]

variance_table = pd.DataFrame({
    "Eigenvalue": eigenvalues,
    "Proportion of Variance": variance_proportion,
    "Cumulative Proportion": cumulative_proportion
}, index=components)

print("PART B1-B4: PCA VARIANCE SUMMARY")
print(variance_table.round(3).to_string())

# 6. Display eigenvectors (component coefficients)
coefficient_table = pd.DataFrame(
    eigenvectors,
    index=X.columns,
    columns=components
)

print("\nPART B5: EIGENVECTORS / COMPONENT COEFFICIENTS")
print(coefficient_table.round(3).to_string())

# 7. Identify the largest absolute coefficients in PC1
pc1_coefficients = coefficient_table["PC1"]
pc1_ranking = pc1_coefficients.abs().sort_values(ascending=False)

print("\nPART B6: PC1 COEFFICIENTS RANKED BY ABSOLUTE VALUE")
print(pd.DataFrame({
    "PC1 Coefficient": pc1_coefficients.loc[pc1_ranking.index],
    "Absolute Coefficient": pc1_ranking
}).round(3).to_string())

# 8. Verify the PCA calculation
print("\nVERIFICATION")
print("Sum of eigenvalues:", round(eigenvalues.sum(), 3))
print("Number of components:", len(eigenvalues))
print("Total variance explained:",
      round(variance_proportion.sum(), 3))

import matplotlib.pyplot as plt

# Part C1: Scree plot
component_numbers = np.arange(1, len(eigenvalues) + 1)

plt.figure(figsize=(8, 5))
plt.plot(component_numbers, eigenvalues, marker="o")
plt.axhline(y=1, linestyle="--", label="Eigenvalue = 1")

plt.xticks(component_numbers)
plt.xlabel("Principal Component")
plt.ylabel("Eigenvalue")
plt.title("Scree Plot: World Happiness Report 2021")
plt.grid(True, alpha=0.3)
plt.legend()
plt.tight_layout()
plt.show()

# Part C3: Kaiser criterion
print("KAISER CRITERION")
for i, value in enumerate(eigenvalues, start=1):
    decision = "Retain" if value > 1 else "Below 1"
    print(f"PC{i}: Eigenvalue = {value:.3f} — {decision}")

# Part C4: Cumulative variance explained
print("\nCUMULATIVE VARIANCE EXPLAINED")
for i, value in enumerate(cumulative_proportion, start=1):
    print(f"First {i} component(s): {value:.3f} ({value*100:.1f}%)")